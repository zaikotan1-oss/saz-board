index = []
for i, p in enumerate(PATTERNS):
    n = sum(1 for q in PATTERNS[:i] if q['map'] == p['map']) + 1
    fn = f"{p['map']}-{n:02d}.json"
    json.dump(p, open(os.path.join(out, fn), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
