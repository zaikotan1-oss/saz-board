"""見本パターンを maps.json の地名（コールアウト）から生成して patterns/*.json と patterns/index.json に書く。
座標は地名の位置＋ずらし。直したい時はここを直して実行し直す（手で JSON を直しても良い）。
使い方:  python tools/make_patterns.py
"""
import json, os, io, sys
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DB = json.load(open(os.path.join(ROOT, 'maps', 'maps.json'), encoding='utf-8'))
MAPS = {m['id']: m for m in DB['maps']}

def C(map_id, name, dx=0, dy=0):
    """地名 → 座標（前方一致で探す）"""
    m = MAPS[map_id]
    for n, x, y in m['callouts']:
        if n == name or n.startswith(name):
            return {'x': x + dx, 'y': y + dy}
    raise KeyError(f'{map_id}: 地名が無い: {name}')

def piece(team, n, role, at, path=(), labels=None):
    labels = labels or {}
    p = {'team': team, 'n': n, 'role': role, 'x': at['x'], 'y': at['y'], 'path': []}
    for i, w in enumerate(path):
        w = dict(w)
        if i in labels:
            w['label'] = labels[i]
        p['path'].append(w)
    return p

def mark(t, at, text=None):
    m = {'type': t, 'x': at['x'], 'y': at['y']}
    if text:
        m['text'] = text
    return m

PATTERNS = []
def add(map_id, title, note, pieces, marks=()):
    PATTERNS.append({'map': map_id, 'title': title, 'note': note, 'pieces': pieces, 'marks': list(marks)})

